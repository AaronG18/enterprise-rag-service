#!/usr/bin/env python3
"""One entry point: rebuild every deliverable the brief asks for.

    python scripts/build_deliverables.py

Why one command: the brief asks for a one-click evaluation script, *and* for the deliverables it
produces (an evaluation report with before/after comparisons, and a log field dictionary with
sample logs). Those used to be three separate commands whose output could - and did - fall out of
step: `run_eval.py` wrote only to `artifacts/`, so the committed report kept quoting a corpus the
repository no longer shipped (#92). One command that regenerates everything removes the step a
reviewer has to remember.

What it produces, and where:

    artifacts/eval/<run>/{metrics.json,report.txt,report.csv,scored_cases.jsonl}
    docs/eval/deterministic-metrics.json     committed snapshot of the deterministic run
    docs/eval/retrieval-comparison.md        generated from the snapshots - never hand-edited
    docs/logging/sample_logs.md              generated by scripts/sample_logs.py
    docs/qa/qa-dashboard.html                generated by scripts/build_qa_dashboard.py

The model-backed retrieval snapshot (`docs/eval/model-backed-retrieval-metrics.json`) is NOT
regenerated here: it needs the local model servers, which CI does not have. It is refreshed with
`python scripts/build_deliverables.py --refresh-model-backed` once those servers are running.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "src"))

from ragserve.evaluation.comparison_doc import render_comparison_doc  # noqa: E402
from ragserve.evaluation.runner import run_evaluation  # noqa: E402

ARTIFACTS = os.path.join(REPO_ROOT, "artifacts")
SNAPSHOT_DETERMINISTIC = os.path.join(REPO_ROOT, "docs", "eval", "deterministic-metrics.json")
SNAPSHOT_MODEL_BACKED = os.path.join(REPO_ROOT, "docs", "eval", "model-backed-retrieval-metrics.json")
COMPARISON_DOC = os.path.join(REPO_ROOT, "docs", "eval", "retrieval-comparison.md")


def write_snapshot(payload: dict, path: str, run_id: str) -> None:
    """Commit a run's numbers so the report - and CI - can read them without re-measuring."""
    metadata = dict(payload["run_metadata"])
    metadata["run_id"] = run_id  # also inside the metadata: the report header reads it from there
    snapshot = {
        "run_id": run_id,
        "run_metadata": metadata,
        "operations": payload["operations"],
        "comparison": payload["comparison"],
        "note": ("Snapshot of a real run, committed so the comparison report and the requirements "
                 "gate can read it without re-measuring. Regenerate with "
                 "python scripts/build_deliverables.py."),
    }
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(snapshot, fh, ensure_ascii=False, sort_keys=True, indent=2)
        fh.write("\n")


def load_snapshot(path: str) -> dict:
    if not os.path.isfile(path):
        return None
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def render_doc() -> str:
    deterministic = load_snapshot(SNAPSHOT_DETERMINISTIC) or {}
    model_backed = load_snapshot(SNAPSHOT_MODEL_BACKED)
    return render_comparison_doc(deterministic, model_backed)


def run_script(relative: str) -> None:
    subprocess.run([sys.executable, os.path.join(REPO_ROOT, "scripts", relative)],
                   cwd=REPO_ROOT, check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-model-backed", action="store_true",
                        help="also re-measure the model-backed retrieval lane (needs the local "
                             "model servers started by scripts/setup_models.py)")
    parser.add_argument("--seed-model-backed", metavar="METRICS_JSON", default=None,
                        help="commit an existing model-backed run (an artifacts/eval/<id>/"
                             "metrics.json) as the model-backed snapshot, without re-measuring")
    parser.add_argument("--corpus", metavar="DIR", default=None,
                        help="index the documents in this directory (.txt, .md, .pdf) instead of "
                             "the built-in synthetic corpus, and write a corpus report. The "
                             "labelled comparison is then not applicable and is skipped rather "
                             "than reported with meaningless numbers.")
    args = parser.parse_args()

    if args.corpus:
        # A user-supplied corpus has no labelled cases, so the comparison and its snapshots stay
        # untouched: overwriting them with numbers measured on someone else's documents would
        # publish a measurement nobody could reproduce.
        from ragserve.evaluation.corpus_report import run_corpus_report  # noqa: E402

        outcome = run_corpus_report(args.corpus, REPO_ROOT, ARTIFACTS)
        report = outcome["report"]
        print("indexed %s" % report["source_dir"])
        print("  documents %s, chunks %s, languages %s"
              % (report["doc_count"], report["chunk_count"], report["per_language"]))
        for item in report.get("skipped_files") or []:
            print("  skipped  %s (%s)" % (item["file"], item["reason"]))
        print("  index build %.3f ms" % report["index_build_ms"])
        print("  recall@5 %s  mrr %s  ndcg %s  context_precision %s"
              % (report["recall@5"], report["mrr"], report["ndcg"], report["context_precision"]))
        print("  p50 %s ms  p95 %s ms  refusal_rate %s"
              % (report["p50_latency_ms"], report["p95_latency_ms"], report["refusal_rate"]))
        print("  provenance %s" % report["provenance"])
        print("  %s" % outcome["paths"]["markdown"])
        return 0

    if args.seed_model_backed:
        with open(args.seed_model_backed, "r", encoding="utf-8") as fh:
            seed = json.load(fh)
        seed_id = os.path.basename(os.path.dirname(os.path.abspath(args.seed_model_backed)))
        write_snapshot(seed, SNAPSHOT_MODEL_BACKED, seed_id)
        print("seeded docs/eval/model-backed-retrieval-metrics.json from %s" % seed_id)

    # The model-backed lane is measured *first*, on purpose: if it is refused we must not have
    # already replaced the deterministic snapshot, or the repository is left half-updated - a new
    # snapshot with a report that still describes the old one.
    model_payload = None
    model_run_id = None
    if args.refresh_model_backed:
        print("1/4 evaluating (model-backed retrieval; needs the local model servers)...")
        os.environ.pop("RAGSERVE_EMBEDDING_PROVIDER", None)
        os.environ.pop("RAGSERVE_RERANKER_PROVIDER", None)
        model_payload = run_evaluation(REPO_ROOT, ARTIFACTS)
        model_run_id = os.path.basename(os.path.dirname(model_payload["artifacts"]["metrics"]))
        provenance = str(model_payload["run_metadata"].get("provenance", ""))
        if "model-backed" not in provenance:
            print("    REFUSED: this run is '%s', not model-backed (no model server reachable)."
                  % provenance)
            print("    Start the two servers from scripts/setup_models.py and re-run. Nothing was "
                  "written: the existing snapshots and report are untouched.")
            return 1

    print("2/4 evaluating (deterministic backend)...")
    # The deterministic lane is the CI baseline, so it is pinned here rather than inherited from
    # whatever the machine happens to have: the published numbers must be reproducible offline,
    # with no model server and no credential.
    os.environ["RAGSERVE_EMBEDDING_PROVIDER"] = "deterministic"
    os.environ["RAGSERVE_RERANKER_PROVIDER"] = "deterministic"
    payload = run_evaluation(REPO_ROOT, ARTIFACTS)
    run_id = os.path.basename(os.path.dirname(payload["artifacts"]["metrics"]))
    write_snapshot(payload, SNAPSHOT_DETERMINISTIC, run_id)
    print("    artifacts/eval/%s/" % run_id)
    print("    docs/eval/deterministic-metrics.json")

    if model_payload is not None:
        write_snapshot(model_payload, SNAPSHOT_MODEL_BACKED, model_run_id)
        print("    docs/eval/model-backed-retrieval-metrics.json")
    else:
        print("2/4 model-backed snapshot kept (use --refresh-model-backed to re-measure it)")

    print("3/4 regenerating the comparison report...")
    document = render_doc()
    with open(COMPARISON_DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(document)
    print("    docs/eval/retrieval-comparison.md")

    print("4/4 regenerating the sample logs and the QA dashboard...")
    run_script("sample_logs.py")
    run_script("build_qa_dashboard.py")
    print("    docs/logging/sample_logs.md")
    print("    docs/qa/qa-dashboard.html")

    print("")
    print("Deliverables regenerated. Next: python scripts/run_tests.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
