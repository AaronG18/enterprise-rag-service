"""Render the comparison report from committed snapshots.

Why this exists: `docs/eval/retrieval-comparison.md` is a deliverable, and it used to be
hand-written. `run_eval.py --all` writes only to `artifacts/`, so nothing regenerated the
document, and it silently kept quoting a corpus the repository no longer shipped for months
(#92). This module makes the document a *product* of the measurements instead of a recollection
of them: the numbers, the bolded winners and the conclusion are all derived from the snapshots, so
the prose cannot disagree with the data it is describing.

The renderer is deterministic - same snapshots in, byte-identical document out - which is what
lets a test assert the committed file equals the generated one.
"""
from __future__ import annotations

from typing import Dict, List, Sequence

# The order the columns and rows appear in. Fixed on purpose: a report that reordered itself
# between runs would be unreadable in a diff.
CONFIGS: Sequence[str] = ("vector_only", "hybrid", "hybrid+rerank")
# The metrics a reviewer is asked to compare, in the order the brief cares about them.
METRICS: Sequence[str] = ("recall@5", "mrr", "ndcg", "context_precision",
                          "faithfulness", "refusal_appropriateness", "style_consistency")

_GENERATED_BANNER = (
    "> **Generated by `python scripts/run.py --eval --all --deliverables` - not hand-written.** The numbers, "
    "the bolded winners and the conclusion are derived from the committed snapshots below, so the "
    "prose cannot drift from the measurements. Edit the snapshots by re-running that script; "
    "editing this file by hand is caught by a test."
)


def _fmt(value) -> str:
    return "%.4f" % value if isinstance(value, (int, float)) else str(value)


def _best_config(comparison: Dict, metric: str):
    """The configuration that strictly leads a metric, or None.

    None also means "do not bold anything": when every configuration scores the same (faithfulness
    and style consistency are 1.0 across the board, for instance) there is no winner, and bolding
    whichever happened to sort first would claim one.
    """
    scored = []
    for name in CONFIGS:
        values = comparison.get(name)
        if not isinstance(values, dict):
            continue
        value = values.get(metric)
        if isinstance(value, (int, float)):
            scored.append((name, value))
    if not scored:
        return None
    top = max(value for _name, value in scored)
    leaders = [name for name, value in scored if value == top]
    return leaders[0] if len(leaders) == 1 else None


def _table(comparison: Dict) -> List[str]:
    rows = ["| Metric | " + " | ".join(CONFIGS) + " |", "|---|" + "---|" * len(CONFIGS)]
    for metric in METRICS:
        best = _best_config(comparison, metric)
        cells = []
        for config in CONFIGS:
            values = comparison.get(config) or {}
            value = values.get(metric)
            if not isinstance(value, (int, float)):
                cells.append("-")
                continue
            cells.append("**%s**" % _fmt(value) if config == best else _fmt(value))
        rows.append("| %s | %s |" % (metric, " | ".join(cells)))
    return rows


def _delta_text(comparison: Dict, metric: str, first: str, second: str) -> str:
    """'0.8987 -> 0.9620' for a metric across two configurations, or '-' if unknown."""
    left = (comparison.get(first) or {}).get(metric)
    right = (comparison.get(second) or {}).get(metric)
    if not isinstance(left, (int, float)) or not isinstance(right, (int, float)):
        return "-"
    return "%s -> %s" % (_fmt(left), _fmt(right))


def _conclusion(comparison: Dict, backend: str) -> List[str]:
    """A conclusion derived from the numbers, not written about them.

    The recommendation is the configuration that leads on the most metrics; ties break towards the
    one that leads on `recall@5`, because a recall miss is the one failure a reranker downstream
    can never repair.
    """
    lines = []
    leaders: Dict[str, int] = {}
    for metric in METRICS:
        best = _best_config(comparison, metric)
        if best:
            leaders[best] = leaders.get(best, 0) + 1
    if leaders:
        winner = max(leaders.items(), key=lambda item: (item[1], item[0] == _best_config(comparison, "recall@5")))[0]
        ranked = ", ".join("%s (%d metrics)" % (name, count)
                           for name, count in sorted(leaders.items(), key=lambda item: -item[1]))
        lines.append("* **Ranking by number of metrics led:** %s." % ranked)
    else:
        winner = None

    lines.append("* **Reranking vs plain hybrid** on this backend:")
    for metric in ("recall@5", "mrr", "ndcg", "context_precision", "refusal_appropriateness"):
        lines.append("  * `%s`: %s" % (metric, _delta_text(comparison, metric, "hybrid", "hybrid+rerank")))
    lines.append("* **Fusion vs vector-only:**")
    for metric in ("recall@5", "mrr"):
        lines.append("  * `%s`: %s" % (metric, _delta_text(comparison, metric, "vector_only", "hybrid")))
    if winner:
        lines.append("* **Recommendation for the %s backend:** `%s`." % (backend, winner))
    return lines


def _section(title: str, snapshot: Dict, backend: str, notes: Sequence[str] = ()) -> List[str]:
    meta = snapshot.get("run_metadata") or {}
    comparison = snapshot.get("comparison") or {}
    lines = ["## %s" % title, ""]
    lines.append("Run `%s` - corpus `%s`, %s labelled cases, provenance `%s`."
                 % (meta.get("run_id", "unknown"), meta.get("corpus_version", "unknown"),
                    meta.get("case_count", "unknown"), meta.get("provenance", "unknown")))
    lines.append("")
    for note in notes:
        lines.append(note)
        lines.append("")
    lines.extend(_table(comparison))
    lines.append("")
    lines.append("### Conclusion (%s)" % backend)
    lines.append("")
    lines.extend(_conclusion(comparison, backend))
    lines.append("")
    return lines


def render_comparison_doc(deterministic: Dict, model_backed: Dict = None) -> str:
    """Render the whole report. Deterministic input gives byte-identical output."""
    lines = ["# Retrieval configuration comparison", "", _GENERATED_BANNER, ""]
    lines.append("Two backends are reported, because they answer different questions and "
                 "**must not be mixed**: the offline deterministic backend (what CI verifies, "
                 "reproducible by anyone) and the model-backed backend (what the shipped default "
                 "actually uses). Provenance is stated with each run.")
    lines.append("")
    lines.extend(_section(
        "Deterministic backend (the CI baseline)", deterministic, "deterministic",
        notes=["Reproduce with `python scripts/run.py --eval --all` (CI pins both stages to "
               "`deterministic`)."]))
    if model_backed:
        lines.extend(_section(
            "Model-backed retrieval (BGE-M3 embeddings + bge-reranker-v2-m3 cross-encoder)",
            model_backed, "model-backed",
            notes=["Embeddings are the real BGE-M3 model served locally (1024-d, keyless) and the "
                   "reranker is a real cross-encoder; generation stays deterministic, so the "
                   "provenance is `model-backed-retrieval, deterministic-generation`.",
                   "Reproduce with `python scripts/run.py --setup` + the two server commands in "
                   "the README, then `python scripts/run.py --eval --all --deliverables`."]))

    # The cross-backend contrast: the two runs disagree about reranking, and that is the finding.
    lines.append("## The contrast between the two backends")
    lines.append("")
    lines.append("| | %s | %s |" % ("deterministic", "model-backed"))
    lines.append("|---|---|---|")
    for label, metric in (("reranking changes recall@5", "recall@5"), ("reranking changes mrr", "mrr")):
        left = _delta_text(deterministic.get("comparison") or {}, metric, "hybrid", "hybrid+rerank")
        right = _delta_text((model_backed or {}).get("comparison") or {}, metric, "hybrid", "hybrid+rerank")
        lines.append("| %s | %s | %s |" % (label, left, right))
    lines.append("")
    lines.append("**Reranking helps exactly when retrieval leaves it room to.** Under hashing "
                 "embeddings the candidate set is poor, so a cross-encoder has something to fix; "
                 "under real embeddings the candidate set is already good and reordering can only "
                 "shuffle a saturated top-5. Neither run is \"the system\" - each is a measurement "
                 "of one backend on one corpus, so this verdict must be re-measured after any "
                 "corpus or embedding change rather than inherited.")
    lines.append("")
    return "\n".join(lines) + "\n"
