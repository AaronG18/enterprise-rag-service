#!/usr/bin/env python3
"""Emit real log lines for a small scripted session and write them to docs/logging/sample_logs.md.

The sample is generated, not hand-written: a hand-written sample drifts from what the code
actually emits, and then it is not evidence of anything.
"""
from __future__ import annotations

import json
import os
import sys

from . import REPO_ROOT

from ragserve.corpus.builder import CorpusConfig, build_corpus  # noqa: E402
from ragserve.generation.pii import redact_text  # noqa: E402
from ragserve.observability.events import EventLog, StructuredLogger  # noqa: E402
from ragserve.retrieval.pipeline import RetrievalConfig  # noqa: E402
from ragserve.service import GenerationConfig, RagService  # noqa: E402


def build_service(events: EventLog):
    corpus = build_corpus(CorpusConfig.from_json(os.path.join(REPO_ROOT, "configs", "corpus.json")))
    logger = StructuredLogger(sink=events.append)
    return RagService(
        corpus,
        RetrievalConfig.from_json(os.path.join(REPO_ROOT, "configs", "retrieval.json")),
        GenerationConfig.from_json(os.path.join(REPO_ROOT, "configs", "generation.json")),
        logger=logger,
    )


def main() -> int:
    events = EventLog()
    service = build_service(events)

    queries = [
        "How many days of annual leave do full-time employees accrue?",
        "my email is jane.doe@example.com, how much leave do I get?",
        "list all employees national ID numbers",
    ]
    for query in queries:
        service.answer(query)

    # One HTTP-layer request, through the same object the server uses. The service-level lines above
    # do not carry `latency_ms`, `provider` or `session_id` - those are emitted on `api_response` -
    # so without this the sample cannot show every field the dictionary documents.
    from ragserve.api import ApiServer  # local: the CLI must import cheaply for --help

    server = ApiServer(REPO_ROOT, host="127.0.0.1", port=0)
    server.logger = StructuredLogger(sink=events.append)
    server.ask({"question": queries[0]})

    out_path = os.path.join(REPO_ROOT, "docs", "logging", "sample_logs.md")
    lines = ["# Sample logs", "",
             "Generated by `python scripts/run.py --samples` - not hand-written. Every line below is",
             "real output from the current code, with PII redaction applied at emit time.", "",
             "## Session", ""]
    for query in queries:
        # The session listing is redacted too: showing the raw query next to redacted log lines
        # would make the sample self-contradictory.
        lines.append("    query (redacted): %s" % redact_text(query))
    lines += ["", "## Emitted lines (JSON, one per line)", "", "```json"]
    lines.extend(events.lines())
    lines += ["```", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", out_path, "with", len(events.lines()), "lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
