#!/usr/bin/env python3
"""Audit the repository against the case-study brief and write the report used for the issue.

    python scripts/run.py --audit                # every clause
    python scripts/run.py --audit --only FR-1    # one clause
    python scripts/run.py --audit --html         # regenerate the HTML too

Writes `docs/qa/requirement-audit.md` and, with --html, `docs/qa/requirement-audit.html`.
The verdicts come from commands run here, so the report cannot claim more than it measured.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

from . import REPO_ROOT

from ragserve.evaluation.audit import audit, render_markdown  # noqa: E402

OUT_DIR = os.path.join(REPO_ROOT, "docs", "qa")

HTML = """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>Requirement audit - Enterprise RAG Service</title>
<style>
 body { font-family: -apple-system, Segoe UI, Roboto, sans-serif; margin: 28px; color: #1a1a1a;
        max-width: 1100px; }
 h1 { font-size: 21px; margin-bottom: 2px; }
 h2 { font-size: 15px; margin-top: 22px; border-bottom: 1px solid #ddd; padding-bottom: 3px; }
 .meta { color: #666; font-size: 12px; }
 .verdict { font-weight: 700; }
 .pass { color: #047857; }
 .fail { color: #b91c1c; }
 pre { background: #f6f7f9; border: 1px solid #e2e4e8; padding: 10px 12px; overflow-x: auto;
       font-size: 12px; line-height: 1.45; }
 table { border-collapse: collapse; font-size: 13px; margin-top: 8px; }
 th, td { border: 1px solid #d8d8d8; padding: 5px 10px; text-align: left; }
 th { background: #f3f4f6; }
 .cmd { color: #374151; font-style: italic; }
</style></head><body>
<h1>Requirement audit against the case-study brief</h1>
<div class="meta">Generated by <code>scripts/run.py</code> on @@STAMP@@ -
every verdict comes from a command run during the audit.</div>
<h2>Summary</h2>
@@SUMMARY@@
<h2>Detail</h2>
@@BODY@@
</body></html>
"""


def render_html(results: list) -> str:
    passed = [r for r in results if r["ok"]]
    summary_rows = "\n".join(
        '<tr><td>%s</td><td>%s</td><td>%s</td><td class="verdict %s">%s</td></tr>'
        % (r["id"], r["clause"], r["title"], "pass" if r["ok"] else "fail",
           "PASS" if r["ok"] else "FAIL") for r in results)
    summary = ('<p><b>%d/%d PASS</b>, %d FAIL</p>'
               '<table><tr><th>id</th><th>clause</th><th>requirement</th><th>verdict</th></tr>'
               '%s</table>' % (len(passed), len(results), len(results) - len(passed),
                               summary_rows))

    body = []
    for item in results:
        body.append('<h2>%s (%s) %s <span class="verdict %s">%s</span></h2>'
                    % (item["id"], item["clause"], item["title"],
                       "pass" if item["ok"] else "fail",
                       "PASS" if item["ok"] else "FAIL"))
        body.append('<p>Target as written: %s</p>' % _escape(item["target"]))
        body.append('<div class="cmd">$ %s</div>' % _escape(item["command"]))
        body.append('<pre>%s</pre>' % _escape(item["output"]))
        body.append('<p class="meta">evidence: <code>%s</code></p>' % _escape(item["evidence"]))
    return (HTML.replace("@@STAMP@@", time.strftime("%Y-%m-%d %H:%M"))
            .replace("@@SUMMARY@@", summary)
            .replace("@@BODY@@", "\n".join(body)))


def _escape(text: str) -> str:
    return (str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", nargs="*", default=None)
    parser.add_argument("--html", action="store_true", help="also write the HTML report")
    parser.add_argument("--json", dest="as_json", action="store_true")
    args = parser.parse_args()

    started = time.perf_counter()
    results = audit(args.only)
    seconds = round(time.perf_counter() - started, 1)

    os.makedirs(OUT_DIR, exist_ok=True)
    markdown = render_markdown(results)
    md_path = os.path.join(OUT_DIR, "requirement-audit.md")
    with open(md_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(markdown)

    if args.html:
        html_path = os.path.join(OUT_DIR, "requirement-audit.html")
        with open(html_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_html(results))
        print("html: %s" % html_path)

    if args.as_json:
        print(json.dumps({"seconds": seconds, "results": results}, ensure_ascii=False, indent=2))

    failed = [r["id"] for r in results if not r["ok"]]
    print("\n%d/%d PASS in %.1fs -> %s" % (len(results) - len(failed), len(results), seconds,
                                           md_path))
    if failed:
        print("FAILED: %s" % ", ".join(failed))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
