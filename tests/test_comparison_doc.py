"""The comparison report is generated, not remembered.

`docs/eval/retrieval-comparison.md` is a deliverable the brief asks for. It used to be written by
hand, and because `run_eval.py --all` writes only to `artifacts/` nothing regenerated it - it kept
quoting a corpus the repository no longer shipped for months (#92). It is now rendered from
committed snapshots by `scripts/build_deliverables.py`, and these tests make that guarantee real:

* the committed file must equal what the renderer produces from the committed snapshots, so a
  hand-edit is a red build instead of a silent divergence;
* the deterministic snapshot must still describe the corpus and case count the repository ships,
  so growing the corpus cannot leave published numbers stale again.
"""
from __future__ import annotations

import json
import os
import unittest

from ragserve.corpus.builder import CorpusConfig, build_corpus
from ragserve.evaluation.comparison_doc import _best_config, render_comparison_doc

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCUMENT = os.path.join(REPO_ROOT, "docs", "eval", "retrieval-comparison.md")
DETERMINISTIC = os.path.join(REPO_ROOT, "docs", "eval", "deterministic-metrics.json")
MODEL_BACKED = os.path.join(REPO_ROOT, "docs", "eval", "model-backed-retrieval-metrics.json")


def read(path: str) -> str:
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def load(path: str) -> dict:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


class TestComparisonDocIsGenerated(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.deterministic = load(DETERMINISTIC)
        cls.model_backed = load(MODEL_BACKED) if os.path.isfile(MODEL_BACKED) else None
        cls.committed = read(DOCUMENT)

    def test_document_declares_it_is_generated(self):
        self.assertIn("Generated by", self.committed,
                      "the document must say how it is produced, like sample_logs.md does")

    def test_committed_document_equals_the_rendered_one(self):
        """A hand-edit must fail. The document is a product of the snapshots, not a recollection."""
        rendered = render_comparison_doc(self.deterministic, self.model_backed)
        self.assertEqual(rendered.strip(), self.committed.strip(),
                         "docs/eval/retrieval-comparison.md differs from what the renderer "
                         "produces from the committed snapshots. Re-run "
                         "python scripts/build_deliverables.py rather than editing it by hand.")

    def test_deterministic_snapshot_describes_the_shipped_corpus(self):
        """The failure this whole module exists to prevent (#92): a corpus grew, the published
        numbers did not, and nothing noticed."""
        corpus = build_corpus(CorpusConfig.from_json(os.path.join(REPO_ROOT, "configs", "corpus.json")))
        metadata = self.deterministic.get("run_metadata") or {}
        self.assertEqual(metadata.get("corpus_version"), corpus.manifest["corpus_version"],
                         "the snapshot measures a different corpus than the repository ships; "
                         "re-run python scripts/build_deliverables.py")
        with open(os.path.join(REPO_ROOT, "eval", "eval_cases.json"), "r", encoding="utf-8") as fh:
            cases = json.load(fh)
        self.assertEqual(metadata.get("case_count"), len(cases),
                         "the snapshot measured a different number of cases than eval_cases.json")

    def test_both_runs_state_their_provenance(self):
        self.assertIn("deterministic", self.committed)
        self.assertIn("model-backed-retrieval", self.committed,
                      "the model-backed run must be reported, tagged, never mixed with the "
                      "deterministic one")

    def test_the_report_names_the_corpus_and_case_count(self):
        metadata = self.deterministic.get("run_metadata") or {}
        self.assertIn(str(metadata.get("corpus_version")), self.committed)
        self.assertIn(str(metadata.get("case_count")), self.committed)


class TestRendererHonesty(unittest.TestCase):
    """The report claims things about the data; the claims must be computed, not assumed."""

    def test_a_tie_is_not_claimed_as_a_win(self):
        """When every configuration scores the same there is no leader, and bolding whichever
        sorts first would invent one."""
        even = {"vector_only": {"faithfulness": 1.0},
                "hybrid": {"faithfulness": 1.0},
                "hybrid+rerank": {"faithfulness": 1.0}}
        self.assertIsNone(_best_config(even, "faithfulness"))

    def test_a_real_leader_is_identified(self):
        uneven = {"vector_only": {"recall@5": 0.7},
                  "hybrid": {"recall@5": 0.9},
                  "hybrid+rerank": {"recall@5": 1.0}}
        self.assertEqual(_best_config(uneven, "recall@5"), "hybrid+rerank")

    def test_missing_metrics_are_not_reported_as_numbers(self):
        sparse = {"hybrid": {"mrr": 0.5}}
        self.assertIsNone(_best_config(sparse, "recall@5"))

    def test_rendering_is_deterministic(self):
        snapshot = load(DETERMINISTIC)
        self.assertEqual(render_comparison_doc(snapshot, None),
                         render_comparison_doc(snapshot, None))


if __name__ == "__main__":
    unittest.main()
